const fs=require('fs'),path=require('path');
const {createClient,toLua}=require('./foreverlogs-review.cjs');
const {createPlayerService}=require('./foreverlogs-players.cjs');
const {randomBytes}=require('crypto');
const {loadKey}=require('./foreverlogs-config.cjs');
function createBridge(root,client=createClient(loadKey(root))){
 let latest=null,busy=false;
 let ownerToken=null;
 const players=createPlayerService(client);
 const ownerActions=new Set(['disconnect','report','actors','reports','review','import','lockOwner']);
 return async function handle(req,res){
  const reply=(status,value)=>{res.writeHead(status,{'Content-Type':'application/json; charset=utf-8','Cache-Control':'no-store'});res.end(JSON.stringify(value));};
  if(req.headers.host!=='127.0.0.1:4317'||(req.headers.origin&&req.headers.origin!=='http://127.0.0.1:4317')||!['127.0.0.1','::ffff:127.0.0.1'].includes(req.socket.remoteAddress)){reply(403,{error:'Use the local preview to connect Forever Logs.'});return;}
  if(req.method==='GET'){reply(200,{configured:client.configured(),mode:'aggregate-statistics'});return;}
  if(req.method!=='POST'||!String(req.headers['content-type']||'').startsWith('application/json')){reply(400,{error:'Expected a local JSON request.'});return;}
  if(busy){reply(409,{error:'A Forever Logs request is already running.'});return;}
  busy=true;
  try{
   let size=0,chunks=[];
   for await(const chunk of req){size+=chunk.length;if(size>16384)throw Error('Request too large.');chunks.push(chunk);}
   let body;try{body=JSON.parse(Buffer.concat(chunks).toString());}catch{throw Error('Invalid request.');}
   if(ownerActions.has(body.action)&&(!ownerToken||req.headers['x-forever-owner-token']!==ownerToken)){reply(403,{error:'Owner access is required for report tools and raw fight details.'});return;}
   switch(body.action){
    case 'connect':{
     if(typeof body.key!=='string'||!body.key.trim())throw Error('Enter the owner API key to unlock owner tools.');
     if(client.configured()&&!client.matchesKey(body.key))throw Error('This is not the key configured for this helper.');
     const reports=await client.connect(body.key);latest=null;ownerToken=randomBytes(32).toString('hex');reply(200,{connected:true,ownerToken,reports});break;
    }
    case 'lockOwner':ownerToken=null;latest=null;reply(200,{locked:true});break;
    case 'disconnect':client.disconnect();players.clear();ownerToken=null;latest=null;reply(200,{connected:false});break;
    case 'aggregateCatalog':reply(200,await client.aggregateCatalog());break;
    case 'rankingBoards':{
     const data=await client.rankingBoards();
     fs.writeFileSync(path.join(root,'addons/ForeverCoaching/Data/ForeverLogsStatistics.lua'),'-- Generated aggregate rankings only. No credentials or individual fight events.\nForeverCoaching=ForeverCoaching or {}\nForeverCoaching.ForeverLogsStatistics='+toLua(data)+'\n');
     reply(200,data);break;
    }
    case 'aggregateStatistics':{
     const data=await client.aggregateStatistics(body.filters);
     fs.writeFileSync(path.join(root,'addons/ForeverCoaching/Data/ForeverLogsStatistics.lua'),'-- Generated aggregate statistics only. No credentials or individual fight events.\nForeverCoaching=ForeverCoaching or {}\nForeverCoaching.ForeverLogsStatistics='+toLua(data)+'\n');
     reply(200,data);break;
    }
    case 'searchPlayers':case 'playerReview':case 'playerStatistics':case 'playerProgress':reply(410,{error:'Player searches, parses and external fight reviews are deferred until release. Use aggregate rankings and statistics.'});break;
    case 'report':latest=null;reply(200,await client.report(body.reportId));break;
    case 'actors':latest=null;reply(200,{actors:await client.actors(body.reportId,body.encounterId)});break;
    case 'reports':reply(200,{reports:await client.listReports(body.offset??0)});break;
    case 'review':latest=null;latest=await client.review(body.reportId,body.encounterId,body.actorId,5,body.context);reply(200,{review:latest});break;
    case 'import':{
     if(!latest)throw Error('Analyze an encounter before importing it.');
     const destination=path.join(root,'addons/ForeverCoaching/Data/ForeverLogsReview.lua');
     fs.writeFileSync(destination,'-- Generated by the local Forever Logs helper. Contains no API key or raw event stream.\nForeverCoaching=ForeverCoaching or {}\nForeverCoaching.ForeverLogsReview='+toLua(latest)+'\n');
     reply(200,{message:'Review saved to the workspace addon. Copy the updated addon to WoW, restart the game, then choose Forever Logs in Combat Review.'});break;
    }
    default:throw Error('Unknown review action.');
   }
  }catch(error){reply(error.statusCode===429?429:400,{error:error.message,...(error.retryAfterSeconds?{retryAfterSeconds:error.retryAfterSeconds}:{})});}finally{busy=false;}
 };
}
module.exports={createBridge};
