// Offline, reproducible import from the pinned engine snapshots and its audits.
const fs=require('fs'),path=require('path');
const {toLua}=require('./foreverlogs-review.cjs');
const revision='a667dce8492bd9fb94269a9f864289cb74006775';
const supplements=JSON.parse(fs.readFileSync(path.join(__dirname,'../docs/research/talent-lesson-supplements.json'),'utf8'));
const confirmed=JSON.parse(fs.readFileSync(path.join(__dirname,'../docs/research/confirmed-talent-effects.json'),'utf8'));
const norm=value=>String(value||'').toLowerCase().replace(/[^a-z0-9]/g,'');
const result={};let count=0;
for(const cls of ['druid','hunter','mage','paladin','priest','rogue','shaman','warlock','warrior']){
 const data=JSON.parse(fs.readFileSync(path.join(__dirname,'../docs/research/talent-effects-'+cls+'.json'),'utf8'));
 const overrides=JSON.parse(fs.readFileSync(path.join(__dirname,'../docs/research/talent-overrides-'+cls+'.json'),'utf8'));
 const entries={};
 for(const tree of data.trees)for(const talent of tree.talents){
  const audit=overrides.overrides.find(o=>o.talent===talent.id&&(!o.tree||norm(o.tree)===norm(tree.id)||norm(o.tree)===norm(tree.name)));
  const t={...talent,...audit?.set};
  entries[t.name]={description:t.description||'',ranks:t.ranks||[],observed:t.ranksObserved||[],rankSource:t.ranksSource||'unspecified',reviewed:t.source?.reviewed===true,
   audited:!!audit,sourceUrl:`https://github.com/sage3648/mythicsim-forever-engine-go/blob/${revision}/tools/forever_talents/data/${cls}.json`,
   auditUrl:audit?`https://github.com/sage3648/mythicsim-forever-engine-go/blob/${revision}/tools/forever_talents/overrides/${cls}.json`:null};count++;
  const confirmations=confirmed.talents[data.className]?.[t.name];
  if(confirmations){
   const confirmedRanks=[],conflictingRanks=[];
   (t.ranks||[]).forEach((values,i)=>{
    if(!confirmations[i])return;
    const description=(t.description||'').replace(/\{(\d+)\}/g,(_,j)=>values[j]??'[unknown]');
    const numbers=(description.match(/\d+(?:\.\d+)?/g)||[]).map(Number);
    (JSON.stringify(numbers)===JSON.stringify(confirmations[i])?confirmedRanks:conflictingRanks).push(i+1);
   });
   Object.assign(entries[t.name],{confirmedRanks,conflictingRanks,confirmationUrl:`https://github.com/sage3648/mythicsim-forever-engine-go/blob/${revision}/assets/confirmed_talents.json`});
  }
 }
 result[cls.toUpperCase()]=entries;
 for(const [name,extra] of Object.entries(supplements[cls.toUpperCase()]||{})){
  entries[name]={description:extra.effect,ranks:[],observed:[],rankSource:'qualitative summary; numeric rank values require current client',reviewed:false,audited:false,
   qualitative:true,optimal:extra.optimal,sourceUrl:`https://github.com/sage3648/mythicsim-forever-engine-go/blob/${revision}/${extra.file}`};
 }
}
fs.writeFileSync(path.join(__dirname,'../addons/ForeverCoaching/Data/TalentLessonEffects.lua'),`-- Generated by tools/Import-TalentLessons.cjs. Pinned engine ${revision}.\n-- Capture/rank provenance is retained; these are not all verified client facts.\nForeverCoaching=ForeverCoaching or {}\nForeverCoaching.TalentLessonEffects=${toLua(result)}\n`);
console.log(`Imported ${count} talent effects across nine classes with rank provenance.`);
